import { describe, it, expect } from "vitest";
import { localDay } from "./day";

describe("localDay", () => {
  it("форматирует локальную дату как YYYY-MM-DD", () => {
    // Конструктор с компонентами создаёт дату в ЛОКАЛЬНОЙ TZ — формат
    // стабилен в любом часовом поясе раннера.
    expect(localDay(new Date(2026, 5, 10))).toBe("2026-06-10");
  });

  it("дополняет месяц и день нулями", () => {
    expect(localDay(new Date(2026, 0, 5))).toBe("2026-01-05");
  });

  it("без аргумента берёт текущую дату и проходит серверную валидацию формата", () => {
    // Тот же regex, которым recordAnswer валидирует clientDay.
    expect(localDay()).toMatch(/^\d{4}-\d{2}-\d{2}$/);
  });

  it("отражает локальный день, а не UTC (полночь по локальному времени)", () => {
    // 23:59 локального 31 декабря — в UTC это может быть уже 1 января, но
    // localDay обязан вернуть локальную дату.
    expect(localDay(new Date(2025, 11, 31, 23, 59))).toBe("2025-12-31");
  });
});
